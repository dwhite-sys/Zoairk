const { test, expect } = require('@playwright/test');
const fs = require('node:fs/promises');
const samples = require('../../examples.json');
const upload = async (page, data, name = 'examples.json') => page.locator('#file-input').setInputFiles({ name, mimeType: 'application/json', buffer: Buffer.from(typeof data === 'string' ? data : JSON.stringify(data)) });
async function getExport(page, id) {
  const pending = page.waitForEvent('download');
  await page.locator(id).click();
  const download = await pending;
  return { name: download.suggestedFilename(), text: await fs.readFile(await download.path(), 'utf8') };
}
test.beforeEach(async ({ page }) => {
  await page.goto('/');
  await expect(page.locator('#load-sample')).toBeEnabled();
});
test('upload, approve, deny, reload, download both datasets and transfer session', async ({ page, browser }) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await upload(page, samples.slice(0, 2));
  await expect(page.locator('#total-count')).toHaveText('2');
  await expect(page.locator('#query')).toHaveText(samples[0].query);
  await expect(page.locator('#reasoning')).toBeVisible();
  await expect(page.locator('#reasoning')).toHaveText(samples[0].reasoning);
  await page.locator('#approve').click();
  await expect(page.locator('#approved-count')).toHaveText('1');
  await expect(page.locator('#query')).toHaveText(samples[1].query);
  await page.locator('#review-reason').fill('Incorrect action order');
  await page.locator('#deny').click();
  await expect(page.locator('#denied-count')).toHaveText('1');
  await expect(page.locator('#queue-empty')).toBeVisible();
  await page.reload();
  await expect(page.locator('#approved-count')).toHaveText('1');
  await expect(page.locator('#denied-count')).toHaveText('1');
  const needle = await getExport(page, '#export-needle');
  expect(needle.name).toBe('needle-approved.jsonl');
  expect(JSON.parse(needle.text)).toEqual(samples[0]);
  const classifier = await getExport(page, '#export-classifier');
  const rows = classifier.text.trim().split('\n').map(JSON.parse);
  expect(rows.map(e => e.label)).toEqual(['approve', 'deny']);
  expect(rows[0].reasoning).toBe(samples[0].reasoning);
  expect(rows[1].review_reason).toBe('Incorrect action order');
  const session = await getExport(page, '#export-session');
  const fresh = await browser.newContext();
  const other = await fresh.newPage();
  await other.goto('/');
  await expect(other.locator('#load-sample')).toBeEnabled();
  await upload(other, session.text, session.name);
  await expect(other.locator('#approved-count')).toHaveText('1');
  await expect(other.locator('#denied-count')).toHaveText('1');
  await fresh.close();
  expect(errors).toEqual([]);
});
test('empty, incorrect and repeated input preserve the current workspace', async ({ page }) => {
  await upload(page, '');
  await expect(page.locator('#notice')).toContainText('empty');
  await expect(page.locator('#total-count')).toHaveText('0');
  await upload(page, samples.slice(0, 2));
  await page.locator('#approve').click();
  await expect(page.locator('#approved-count')).toHaveText('1');
  await upload(page, '{broken');
  await expect(page.locator('#notice')).toContainText('Invalid JSON');
  await expect(page.locator('#total-count')).toHaveText('2');
  await upload(page, samples.slice(0, 2));
  await expect(page.locator('#notice')).toContainText('2 duplicates skipped');
  await expect(page.locator('#approved-count')).toHaveText('1');
  const malformed = structuredClone(samples[0]);
  delete malformed.answers[0].arguments.target;
  await upload(page, [samples[2], malformed]);
  await expect(page.locator('#notice')).toContainText('missing "target"');
  await expect(page.locator('#total-count')).toHaveText('2');
});
test('undo and reclassification remove obsolete dataset labels', async ({ page }) => {
  await upload(page, [samples[0]]);
  await page.locator('#approve').click();
  await expect(page.locator('#approved-count')).toHaveText('1');
  await page.locator('#undo').click();
  await expect(page.locator('#approved-count')).toHaveText('0');
  await expect(page.locator('#query')).toBeVisible();
  await page.locator('#deny').click();
  await expect(page.locator('#denied-count')).toHaveText('1');
  await expect(page.locator('#export-needle')).toBeDisabled();
  await page.locator('[data-filter="reviewed"]').click();
  await page.locator('#clear-decision').click();
  await expect(page.locator('#denied-count')).toHaveText('0');
  await expect(page.locator('#export-classifier')).toBeDisabled();
});
test('sample and review screen fit the viewport; imported markup stays literal', async ({ page }, testInfo) => {
  await page.screenshot({ path: testInfo.outputPath('empty.png'), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.locator('#load-sample').click();
  await expect(page.locator('#total-count')).toHaveText('10');
  const malicious = structuredClone(samples[0]);
  malicious.query = '<img src=x onerror="window.injected=true">';
  await upload(page, [malicious]);
  await page.locator('[data-filter="all"]').click();
  for (let i = 0; i < 10; i++) await page.locator('#next').click();
  await expect(page.locator('#query')).toHaveText(malicious.query);
  await expect(page.locator('#query img')).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.locator('#previous').click();
  await expect(page.locator('#reasoning')).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('review.png'), fullPage: true });
});
