const { test, expect } = require('@playwright/test');
async function connect(page) {
  await page.locator('#connection-settings > summary').click();
  await page.locator('#ws-url').fill('ws://127.0.0.1:8083/ws');
  await page.locator('#connection-form').getByRole('button', { name: 'Connect', exact: true }).click();
  await expect(page.locator('#ws-status')).toHaveText('Backend connected');
  await page.locator('#connection-settings > summary').click();
}
async function minimumWorld(page) {
  await page.getByRole('link', { name: 'Create a game', exact: false }).click();
  await page.getByLabel('Area name', { exact: true }).fill('Hollow Coast');
  await page.getByLabel('Description', { exact: true }).fill('A coast under a silver moon.');
  await page.getByRole('button', { name: '+ Add scene', exact: true }).click();
  const scene = page.locator('[data-kind="Scene"]').first();
  await scene.getByLabel('Scene name', { exact: true }).fill('Harbor');
  await scene.getByLabel('Scene description', { exact: true }).fill('A quiet pier with a locked gate.');
  await page.getByRole('button', { name: '+ Create player', exact: true }).click();
  await page.getByLabel('Character name', { exact: true }).fill('Mira');
  return scene;
}
test.beforeEach(async ({ page }) => { await page.goto('/'); });
test('main menu routes independently to creation and play and supports browser back', async ({ page }, testInfo) => {
  await expect(page.getByRole('heading', { name: 'Welcome to Zoairk.' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('home.png'), fullPage: true });
  await page.getByRole('link', { name: 'Create a game', exact: false }).click();
  await expect(page.locator('#view-create')).toBeVisible();
  await page.goBack();
  await expect(page.locator('#view-home')).toBeVisible();
  await page.getByRole('link', { name: 'Play a game', exact: false }).click();
  await expect(page.locator('#view-play')).toBeVisible();
});
test('nested editor commits exact ownership and plays streamed WebSocket output', async ({ page }, testInfo) => {
  const frames = [], errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('websocket', socket => socket.on('framesent', frame => { try { frames.push(JSON.parse(frame.payload)); } catch {} }));
  await connect(page);
  const scene = await minimumWorld(page);
  await scene.getByRole('button', { name: '+ Add object', exact: true }).click();
  const sceneObject = scene.locator('[data-kind="Object"]').first();
  await sceneObject.getByLabel('Object name', { exact: true }).fill('Gate');
  await sceneObject.getByLabel('Object description', { exact: true }).fill('An old iron gate.');
  await sceneObject.getByLabel('Object state', { exact: true }).selectOption('locked');
  await scene.getByRole('button', { name: '+ Add NPC', exact: true }).click();
  const npc = scene.locator('[data-kind="NPC"]');
  await npc.getByLabel('NPC name', { exact: true }).fill('Guard');
  await npc.getByLabel('NPC description', { exact: true }).fill('A tired watchman.');
  await npc.getByRole('button', { name: '+ Add object', exact: true }).click();
  await npc.getByLabel('Object name', { exact: true }).fill('Brass key');
  const player = page.locator('[data-kind="Player"]');
  await player.getByRole('button', { name: '+ Add item', exact: true }).click();
  await player.getByLabel('Object name', { exact: true }).fill('Lantern');
  await player.getByRole('button', { name: '+ Add backstory', exact: true }).click();
  await player.getByLabel('Backstory', { exact: true }).fill('A sailor returning home.');
  await page.getByRole('button', { name: '+ Add scene', exact: true }).click();
  const second = page.locator('[data-kind="Scene"]').nth(1);
  await second.getByLabel('Scene name', { exact: true }).fill('Forest');
  await scene.getByRole('button', { name: '+ Add exit', exact: true }).click();
  await scene.getByLabel('Exit name or direction', { exact: true }).fill('north');
  await scene.getByLabel('Destination scene', { exact: true }).selectOption(await second.getAttribute('data-entity-id'));
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Commit world', exact: true }).click();
  // Repeated submit events must not send a second world while awaiting confirmation.
  await page.locator('#world-form').evaluate(form => { form.requestSubmit(); form.requestSubmit(); });
  await expect(page.locator('#upload-status')).toContainText('world JSON received and validated');
  const commits = frames.filter(frame => frame.type === 'create_game');
  expect(commits).toHaveLength(1);
  const world = commits[0].payload;
  const harbor = world.areas[0].scenes[0];
  expect(harbor.objects[0].owner).toEqual({ type: 'scene', id: harbor.id });
  expect(harbor.objects[0].state).toBe('locked');
  expect(harbor.npcs[0].objects[0].owner).toEqual({ type: 'npc', id: harbor.npcs[0].id });
  expect(world.player.objects[0].owner).toEqual({ type: 'player', id: world.player.id });
  expect(world.player.backstory).toBe('A sailor returning home.');
  expect(world.player.startingSceneId).toBe(harbor.id);
  expect(harbor.exits[0].destinationSceneId).toBe(world.areas[0].scenes[1].id);
  expect(world.player.stats).toBeNull();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: testInfo.outputPath('builder.png') });
  await page.getByRole('link', { name: '← Main menu', exact: true }).click();
  await page.getByRole('link', { name: 'Play a game', exact: false }).click();
  await expect(page.locator('#terminal-output')).toContainText('Protocol test output. Harbor');
  const beforeEmpty = frames.length;
  await page.locator('#command-input').fill('   ');
  await page.locator('#terminal-form').getByRole('button', { name: 'Send', exact: true }).click();
  expect(frames).toHaveLength(beforeEmpty);
  await page.locator('#command-input').fill('unlock gate');
  await page.locator('#terminal-form').getByRole('button', { name: 'Send', exact: true }).click();
  await expect(page.locator('.msg.engine').last()).toHaveText('Protocol test: unlock gate');
  await page.locator('#command-input').press('ArrowUp');
  await expect(page.locator('#command-input')).toHaveValue('unlock gate');
  await page.screenshot({ path: testInfo.outputPath('play.png'), fullPage: true });
  expect(errors).toEqual([]);
});
test('empty worlds, invalid exits and absent backend do not claim success or lose drafts', async ({ page }) => {
  await page.getByRole('link', { name: 'Create a game', exact: false }).click();
  await page.getByRole('button', { name: 'Commit world', exact: true }).click();
  await expect(page.locator('#upload-status')).toContainText('Give the area a name');
  await page.getByRole('link', { name: '← Main menu', exact: true }).click();
  const scene = await minimumWorld(page);
  await page.getByRole('button', { name: 'Commit world', exact: true }).click();
  await expect(page.locator('#upload-status')).toContainText('connect to the backend first');
  await scene.getByRole('button', { name: '+ Add exit', exact: true }).click();
  await scene.getByLabel('Exit name or direction', { exact: true }).fill('east');
  await page.getByRole('button', { name: 'Commit world', exact: true }).click();
  await expect(page.locator('#upload-status')).toContainText('destination scene');
  await expect(page.getByLabel('Area name', { exact: true })).toHaveValue('Hollow Coast');
});
test('text stays literal; disconnected commands stay in the input; bad backend messages are handled', async ({ page }) => {
  const scene = await minimumWorld(page);
  await scene.getByLabel('Scene name', { exact: true }).fill('<img src=x onerror="alert(1)">');
  await expect(scene.locator('.entity-title').first()).toHaveText('<img src=x onerror="alert(1)">');
  await expect(scene.locator('img')).toHaveCount(0);
  await connect(page);
  await page.getByRole('link', { name: '← Main menu', exact: true }).click();
  await page.getByRole('link', { name: 'Play a game', exact: false }).click();
  for (const [command, expected] of [['fixture:error', 'command rejected'], ['fixture:malformed', 'unsupported backend message']]) {
    await page.locator('#command-input').fill(command);
    await page.locator('#terminal-form').getByRole('button', { name: 'Send', exact: true }).click();
    await expect(page.locator('#play-status')).toContainText(expected);
  }
  await page.locator('#command-input').fill('fixture:disconnect');
  await page.locator('#terminal-form').getByRole('button', { name: 'Send', exact: true }).click();
  await expect(page.locator('#ws-status')).toHaveText('Backend disconnected');
  await page.locator('#command-input').fill('take lantern');
  await page.locator('#terminal-form').getByRole('button', { name: 'Send', exact: true }).click();
  await expect(page.locator('#play-status')).toContainText('Cannot send');
  await expect(page.locator('#command-input')).toHaveValue('take lantern');
});
